-- Run this in the Supabase SQL Editor to initialize persistent cloud storage tables

-- 1. Custom Lexicon (Pronunciation Rules & Sound-Alikes)
CREATE TABLE IF NOT EXISTS custom_lexicon (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    misheard_phrase TEXT NOT NULL,
    correct_term TEXT NOT NULL,
    modality TEXT DEFAULT 'all',
    doctor_id TEXT DEFAULT 'default_doctor',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_custom_lexicon_misheard ON custom_lexicon (LOWER(misheard_phrase));
CREATE INDEX IF NOT EXISTS idx_custom_lexicon_modality ON custom_lexicon (modality);

-- 2. Custom Voice Macros
CREATE TABLE IF NOT EXISTS custom_macros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_phrase TEXT NOT NULL UNIQUE,
    expansion_text TEXT NOT NULL,
    modality TEXT DEFAULT 'all',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_custom_macros_trigger ON custom_macros (LOWER(trigger_phrase));

-- 3. Saved Reports (Radiology & Nuclear Medicine)
CREATE TABLE IF NOT EXISTS saved_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_name TEXT DEFAULT 'Synthetic Patient',
    age_gender TEXT DEFAULT '45Y / M',
    modality TEXT DEFAULT 'CT',
    template_key TEXT DEFAULT 'ct_brain',
    raw_transcript TEXT,
    final_report_html TEXT,
    patient_summary TEXT,
    status TEXT DEFAULT 'DRAFT',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_saved_reports_created ON saved_reports (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_saved_reports_modality ON saved_reports (modality);

-- 4. Hospital Letterhead Calibration Settings
CREATE TABLE IF NOT EXISTS letterhead_settings (
    id TEXT PRIMARY KEY DEFAULT 'default_hospital',
    preprinted_letterhead BOOLEAN DEFAULT FALSE,
    top_margin_mm INTEGER DEFAULT 45,
    bottom_margin_mm INTEGER DEFAULT 30,
    include_summary_page2 BOOLEAN DEFAULT FALSE,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- Seed default initial row for letterhead settings
INSERT INTO letterhead_settings (id, preprinted_letterhead, top_margin_mm, bottom_margin_mm, include_summary_page2)
VALUES ('default_hospital', FALSE, 45, 30, FALSE)
ON CONFLICT (id) DO NOTHING;

-- 5. Live Teleradiology Worklist Queue & SLA Tracking
CREATE TABLE IF NOT EXISTS worklist_studies (
    id TEXT PRIMARY KEY,
    uhid TEXT NOT NULL,
    patient_name TEXT NOT NULL,
    age_gender TEXT NOT NULL,
    patient_phone TEXT NOT NULL,
    referring_doctor TEXT NOT NULL,
    modality TEXT NOT NULL,
    template_key TEXT NOT NULL,
    study_name TEXT NOT NULL,
    clinical_history TEXT NOT NULL,
    priority TEXT NOT NULL DEFAULT 'ROUTINE',
    status TEXT NOT NULL DEFAULT 'PENDING',
    sla_target_minutes INTEGER NOT NULL DEFAULT 30,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
    signed_at TIMESTAMP WITH TIME ZONE,
    final_report_html TEXT,
    patient_summary TEXT
);

CREATE INDEX IF NOT EXISTS idx_worklist_priority_status ON worklist_studies (priority, status);
CREATE INDEX IF NOT EXISTS idx_worklist_created ON worklist_studies (created_at ASC);
